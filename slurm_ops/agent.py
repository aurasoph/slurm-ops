def _locate_dotenv(start: Path) -> Optional[Path]:
    """Walk upward from `start` looking for a `.env` (or `agent/.env`)."""
    cur = start.resolve()
    for _ in range(8):
        for cand in (cur / ".env", cur / "agent" / ".env"):
            if cand.is_file():
                return cand
        if cur == cur.parent: break
        cur = cur.parent
    return None


def run_loop(
    project_root: Path,
    *,
    instructions_path: Optional[Path] = None,
    session_instructions: str = "",
) -> int:
    project_context = inspect_project(project_root, instructions_path=instructions_path)
    intro_lines = [
        "",
        "  gcd-agent  —  slash-command REPL over a Lean project + vLLM",
        f"  project    : {project_root}",
        f"  package    : {project_context.package_name or '(unknown)'}",
        f"  toolchain  : {project_context.toolchain or '(unknown)'}",
        f"  source     : {', '.join(project_context.source_roots) or '(none detected)'}",
        f"  sorry/admit: {project_context.sorry_like_count}",
        f"  endpoint   : {_env_label('OPENAI_BASE_URL', DEFAULT_BASE_URL)}",
        f"  model      : {_env_label('VLLM_MODEL', DEFAULT_MODEL)}",
        "",
        "  commands   : context, chat QUESTION, instructions, list, show N, ask N,",
        "               try N, build [MODULE], env, quit",
        "               (you can also just type a project question)",
        "               (type `help <cmd>` for details)",
        "",
    ]
    shell = AgentShell(
        project_root,
        project_context=project_context,
        instructions_path=instructions_path,
        session_instructions=session_instructions,
    )
    shell.intro = "\n".join(intro_lines)
    try:
        shell.cmdloop()
    except KeyboardInterrupt:
        print()
        return 130
    return 0


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(prog="gcd-agent",
        description="Slash-command REPL over a Lean project + vLLM endpoint.")
    ap.add_argument("--project", type=Path, default=None,
        help="Path to the Lean project root. Defaults to $LEAN_REPO_PATH "
             "(loaded from .env if needed).")
    ap.add_argument("--env-file", type=Path, default=None,
        help="Explicit path to a .env file; otherwise search cwd and upward.")
    ap.add_argument("--instructions", type=Path, default=None,
        help="Path to a project instruction file. Defaults to .gcd/agent.md, "
             ".gcd/context.md, .gcd/instructions.md, or AGENTS.md if present.")
    ap.add_argument("--context", action="append", default=[],
        help="Inline session instruction to include in every vLLM prompt. "
             "May be passed more than once.")
    args = ap.parse_args(argv)

    env_path = args.env_file or _locate_dotenv(Path.cwd())
    if env_path:
        load_env_file(env_path)

    if args.project is not None:
        project = args.project
    elif "LEAN_REPO_PATH" in os.environ:
        project = Path(os.environ["LEAN_REPO_PATH"])
    else:
        sys.stderr.write(
            "gcd-agent: no Lean project path.\n"
            "  Set LEAN_REPO_PATH in your shell, put it in a .env file next\n"
            "  to the agent (see agent/.env.example), or pass --project PATH.\n"
        )
        return 2

    project = project.expanduser().resolve()
    if not (project / "lakefile.lean").is_file() and not (project / "lakefile.toml").is_file():
        sys.stderr.write(f"gcd-agent: {project} has no lakefile.lean / lakefile.toml\n")
        return 2

    env_instructions = os.environ.get("LEAN_AGENT_CONTEXT", "").strip()
    session_instructions = "\n\n".join(
        part for part in [env_instructions, *args.context]
        if part and part.strip()
    )
    instructions_path = args.instructions
    if instructions_path is None and os.environ.get("LEAN_AGENT_INSTRUCTIONS"):
        instructions_path = Path(os.environ["LEAN_AGENT_INSTRUCTIONS"])

    return run_loop(
        project,
        instructions_path=instructions_path,
        session_instructions=session_instructions,
    )


if __name__ == "__main__":
    raise SystemExit(main())
