def _read_text_limited(path: Path, *, max_chars: int = 4000) -> str:
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return ""
    if len(text) > max_chars:
        return text[:max_chars].rstrip() + "\n..."
    return text.strip()


def _run_quiet(cmd: list[str], cwd: Path) -> Optional[str]:
    try:
        r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode != 0:
        return None
    return r.stdout.strip()


def _detect_lakefile(root: Path) -> Optional[Path]:
    for name in ("lakefile.lean", "lakefile.toml"):
        path = root / name
        if path.is_file():
            return path
    return None


def _parse_lakefile_lean(path: Path) -> tuple[Optional[str], list[str]]:
    text = _read_text_limited(path, max_chars=20000)
    package_name = None
    deps: list[str] = []

    m = re.search(r"^\s*package\s+([A-Za-z0-9_'.-]+)", text, re.MULTILINE)
    if m:
        package_name = m.group(1).strip('"')

    for m in re.finditer(r"^\s*require\s+([A-Za-z0-9_'.-]+)", text, re.MULTILINE):
        dep = m.group(1).strip('"')
        if dep not in deps:
            deps.append(dep)
    return package_name, deps


def _parse_lakefile_toml(path: Path) -> tuple[Optional[str], list[str]]:
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return None, []

    package = data.get("package", {})
    package_name = package.get("name") if isinstance(package, dict) else None
    deps: list[str] = []
    raw_deps = data.get("require") or data.get("dependencies") or []
    if isinstance(raw_deps, list):
        for item in raw_deps:
            if isinstance(item, dict) and isinstance(item.get("name"), str):
                deps.append(item["name"])
            elif isinstance(item, str):
                deps.append(item)
    elif isinstance(raw_deps, dict):
        deps.extend(str(k) for k in raw_deps)
    return package_name, deps


def _detect_package(root: Path, lakefile: Optional[Path]) -> tuple[Optional[str], list[str]]:
    if lakefile is None:
        return None, []
    if lakefile.name == "lakefile.toml":
        return _parse_lakefile_toml(lakefile)
    return _parse_lakefile_lean(lakefile)


def _lean_files(root: Path) -> list[Path]:
    skip = {".lake", "lake-packages", ".git"}
    return sorted(
        p for p in root.rglob("*.lean")
        if not any(part in skip for part in p.parts)
        and p.name != "lakefile.lean"
    )


def _detect_source_roots(root: Path, files: list[Path]) -> list[str]:
    roots: set[str] = set()
    for path in files:
        try:
            rel = path.relative_to(root)
        except ValueError:
            continue
        if rel.name == "lakefile.lean":
            continue
        roots.add(rel.parts[0] if len(rel.parts) > 1 else ".")
    return sorted(roots)


def _count_sorry_like(files: list[Path]) -> int:
    count = 0
    for path in files:
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        count += len(re.findall(r"\b(sorry|admit)\b", text))
    return count


def load_project_instructions(
    project_root: Path,
    explicit_path: Optional[Path] = None,
) -> tuple[str, list[str]]:
    """Load project-specific guidance for the agent.

    Default files are intentionally explicit and small: `.gcd/agent.md`,
    `.gcd/context.md`, `.gcd/instructions.md`, and `AGENTS.md`. The first
    existing files are concatenated and included in every vLLM request.
    """
    root = Path(project_root).expanduser().resolve()
    paths: list[Path]
    if explicit_path is not None:
        p = explicit_path.expanduser()
        paths = [p if p.is_absolute() else root / p]
    else:
        paths = [root / name for name in DEFAULT_INSTRUCTION_FILES]

    chunks: list[str] = []
    used: list[str] = []
    for path in paths:
        if not path.is_file():
            continue
        text = _read_text_limited(path, max_chars=8000)
        if not text:
            continue
        used.append(str(path))
        chunks.append(f"# {path.name}\n{text}")
    return "\n\n".join(chunks).strip(), used


