def _strip_think(text: str) -> str:
    """Remove Qwen3-style <think>...</think> reasoning blocks from a reply."""
    text = re.sub(r"<think>.*?</think>\s*", "", text, flags=re.DOTALL)
    text = re.sub(r"<think>.*", "", text, flags=re.DOTALL)
    return text.strip()


def _extract_lean_block(text: str) -> str:
    """Pull the body of the first ```lean ... ``` fence, else the whole text."""
    text = _strip_think(text)
    m = re.search(r"```(?:lean4?|lean)?\s*\n(.*?)```", text, re.DOTALL)
    return m.group(1).strip() if m else text.strip()


def ask_for_proof(
    decl_name: str,
    signature: str,
    surrounding_context: str,
    *,
    project_context: Optional[LeanProjectContext | str] = None,
    imports: str = "",
    diagnostic_message: str = "",
    extra_instructions: str = "",
    model: Optional[str] = None,
    max_tokens: int = 2048,
    temperature: float = 0.0,
    timeout_s: int = 120,
) -> Proposal:
    """Send a single sorry to vLLM and return the candidate replacement."""
    chosen = model or resolved_model()
    if isinstance(project_context, LeanProjectContext):
        project_block = render_project_context(
            project_context,
            extra_instructions=extra_instructions,
        )
    else:
        project_block = (project_context or "").strip()

    context_parts = []
    if project_block:
        context_parts.append(project_block)
    if imports.strip():
        context_parts.append(f"File imports:\n```lean\n{imports.strip()}\n```")
    if diagnostic_message.strip():
        context_parts.append(f"Lean diagnostic:\n{diagnostic_message.strip()}")
    context_parts.append(
        f"Declaration: {decl_name}\n\n"
        f"Signature:\n```lean\n{signature}\n```\n\n"
        f"Surrounding file context (the `sorry` is inside this declaration):\n"
        f"```lean\n{surrounding_context}\n```"
    )
    user = (
        "\n\n".join(context_parts)
        + "\n\nReplace the current declaration with a version that preserves "
        "the statement and fills the proof. Output only the full replacement "
        "declaration, inside one ```lean ... ``` block.\n\n/no_think"
    )
    base_url = resolved_base_url()
    api_key = resolved_api_key()
    payload = {
        "model": chosen,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user},
        ],
        "max_tokens": max_tokens,
        "temperature": temperature,
    }
    resp = _post_json(f"{base_url}/chat/completions", payload, api_key=api_key, timeout_s=timeout_s)
    msg = resp["choices"][0]["message"]["content"] or ""
    usage = resp.get("usage") or {}
    return Proposal(
        raw=msg,
        proof=_extract_lean_block(msg),
        model=chosen,
        prompt_tokens=int(usage.get("prompt_tokens") or 0),
        completion_tokens=int(usage.get("completion_tokens") or 0),
    )


