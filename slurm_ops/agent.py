def _flatten_symbols(symbols: list[dict]) -> list[dict]:
    out: list[dict] = []
    def visit(s):
        out.append(s)
        for c in s.get("children", []) or []: visit(c)
    for s in symbols: visit(s)
    return out


def _enclosing_symbol(symbols_flat: list[dict], line: int) -> Optional[dict]:
    cands = []
    for s in symbols_flat:
        rng = s.get("range") or s.get("location", {}).get("range")
        if not rng: continue
        sl, el = rng["start"]["line"], rng["end"]["line"]
        if sl <= line <= el:
            cands.append((el - sl, s))
    if not cands: return None
    cands.sort(key=lambda x: x[0])
    return cands[0][1]


def _extract_signature(lines: list[str], start_line_0: int) -> str:
    out = []
    for i in range(start_line_0, min(len(lines), start_line_0 + 20)):
        out.append(lines[i])
        stripped = lines[i].strip()
        if ":= by" in stripped or stripped.endswith(":="):
            break
        if "sorry" in stripped:
            break
    return "\n".join(out)


def _extract_imports(lines: list[str]) -> str:
    imports = []
    for line in lines[:200]:
        stripped = line.strip()
        if stripped.startswith("import "):
            imports.append(line)
        elif stripped and not stripped.startswith("--") and imports:
            break
    return "\n".join(imports)


def _sorry_like_diagnostics(lines: list[str], existing: list[dict]) -> list[dict]:
    """Add text-search sorry/admit hits when Lean diagnostics are quiet."""
    seen_lines = {
        d.get("range", {}).get("start", {}).get("line")
        for d in existing
    }
    out = list(existing)
    for idx, line in enumerate(lines):
        if idx in seen_lines:
            continue
        if re.search(r"\b(sorry|admit)\b", line):
            out.append({
                "range": {"start": {"line": idx}, "end": {"line": idx}},
                "message": "syntactic sorry/admit placeholder",
            })
    return out


def _dedupe_hits(hits: list[SorryHit]) -> list[SorryHit]:
    by_decl: dict[tuple[str, str, tuple[int, int]], SorryHit] = {}
    for hit in hits:
        key = (hit.file, hit.decl_name, hit.decl_range)
        current = by_decl.get(key)
        if current is None:
            by_decl[key] = hit
            continue
        if current.diagnostic_message.startswith("syntactic ") and not hit.diagnostic_message.startswith("syntactic "):
            by_decl[key] = hit
    return list(by_decl.values())


def _hit_sort_key(hit: SorryHit) -> tuple[str, int, str]:
    return (hit.file, hit.decl_range[0], hit.decl_name)


def find_sorrys(project_root, files: Optional[list[str]] = None) -> list[SorryHit]:
    """List every `sorry` in `project_root` flagged by the Lean compiler."""
    root = Path(project_root).resolve()
    if files is None:
        targets = sorted(
            p for p in root.rglob("*.lean")
            if ".lake" not in p.parts and "lake-packages" not in p.parts
            and p.name != "lakefile.lean"
        )
    else:
        targets = [Path(f) if Path(f).is_absolute() else root / f for f in files]

    hits: list[SorryHit] = []
    with _LeanLSP(root) as lsp:
        for path in targets:
            text_lines = path.read_text(encoding="utf-8").splitlines()
            diags = lsp.open_and_wait(path)
            sorry_diags = [d for d in diags if "sorry" in (d.get("message") or "").lower()]
            sorry_diags = _sorry_like_diagnostics(text_lines, sorry_diags)
            if not sorry_diags:
                continue
            imports = _extract_imports(text_lines)
            symbols = _flatten_symbols(lsp.document_symbols(path))
            for d in sorry_diags:
                rng = d.get("range", {})
                start_line_0 = rng.get("start", {}).get("line", 0)
                sym = _enclosing_symbol(symbols, start_line_0)
                if sym:
                    sl = sym["range"]["start"]["line"]
                    el = sym["range"]["end"]["line"]
                    name = sym.get("name", "?")
                else:
                    sl = max(0, start_line_0 - 5)
                    el = min(len(text_lines) - 1, start_line_0 + 5)
                    name = "?"
                ctx_start = max(0, sl - 5)
                ctx_end = min(len(text_lines), el + 5)
                hits.append(SorryHit(
                    file=str(path),
                    line=start_line_0 + 1,
                    decl_name=name,
                    decl_range=(sl + 1, el + 1),
                    imports=imports,
                    signature=_extract_signature(text_lines, sl),
                    surrounding="\n".join(text_lines[ctx_start:ctx_end]),
                    diagnostic_message=d.get("message", ""),
                ))
    return sorted(_dedupe_hits(hits), key=_hit_sort_key)


