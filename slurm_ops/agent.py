@dataclass
class Attempt:
    file: str
    decl_name: str
    candidate: str
    accepted: bool
    build_stdout: str
    build_stderr: str


def _module_name_for(project_root: Path, lean_file: Path) -> Optional[str]:
    try:
        rel = lean_file.resolve().relative_to(project_root.resolve())
    except ValueError:
        return None
    if rel.suffix != ".lean": return None
    return ".".join(rel.with_suffix("").parts)


def splice(text: str, hit: SorryHit, replacement: str) -> str:
    """Substitute the entire enclosing declaration with `replacement`."""
    lines = text.splitlines(keepends=True)
    start, end = hit.decl_range[0] - 1, hit.decl_range[1] - 1
    head = "".join(lines[:start])
    tail = "".join(lines[end + 1:])
    middle = replacement.rstrip() + "\n"
    return head + middle + tail


def lake_build(project_root: Path, module: Optional[str] = None) -> tuple[int, str, str]:
    cmd = ["lake", "build"] + ([module] if module else [])
    r = subprocess.run(cmd, cwd=project_root, capture_output=True, text=True)
    return r.returncode, r.stdout, r.stderr


def _snapshot(path: Path) -> Path:
    tmp = Path(tempfile.mkdtemp(prefix="gcd-agent-")) / path.name
    shutil.copy2(path, tmp)
    return tmp


