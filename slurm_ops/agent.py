class AgentShell(cmd.Cmd):
    """Interactive slash-command shell over the Lean project + vLLM."""

    intro = ""   # set in main()
    prompt = "gcd> "

    def __init__(
        self,
        project_root: Path,
        *,
        project_context: Optional[LeanProjectContext] = None,
        instructions_path: Optional[Path] = None,
        session_instructions: str = "",
    ) -> None:
        super().__init__()
        self.project_root = project_root
        self.instructions_path = instructions_path
        self.project_context = project_context or inspect_project(project_root)
        self.session_instructions = session_instructions.strip()
        self.hits: list[SorryHit] = []
        # last proposal per index (1-based), so `try N` knows what to apply.
        self.proposals: dict[int, Proposal] = {}

    # -- helpers -----------------------------------------------------------

    def _need_hits(self) -> bool:
        if not self.hits:
            print("(no sorry index loaded yet — run `list` first)")
            return True
        return False

    def _idx(self, arg: str) -> Optional[int]:
        try:
            n = int(arg.strip())
        except ValueError:
            print(f"expected an integer index, got {arg!r}")
            return None
        if n < 1 or n > len(self.hits):
            print(f"index out of range; have {len(self.hits)} sorrys")
            return None
        return n

    def _chat(self, question: str) -> None:
        question = question.strip()
        if not question:
            print("usage: chat QUESTION")
            return
        print("[agent] asking vLLM about the project...")
        try:
            answer = ask_project_question(
                question,
                project_context=self.project_context,
                extra_instructions=self.session_instructions,
            )
        except Exception as e:
            print(f"[agent] vLLM call failed: {e}")
            print(f"[agent] endpoint = {resolved_base_url()}")
            print("[agent] local context is still available with `context`.")
            return
        print(answer)

    # -- commands ----------------------------------------------------------

    def do_list(self, arg: str) -> None:
        """list  —  scan the project for sorrys via Lean LSP (~30s warmup first time)."""
        print(f"[agent] scanning {self.project_root} via Lean LSP...")
        try:
            self.hits = find_sorrys(self.project_root)
        except FileNotFoundError as e:
            print(f"[agent] {e}; is `lake` on PATH and the project usable?")
            return
        if not self.hits:
            print("(no sorrys found)")
            return
        w = len(str(len(self.hits)))
        for i, h in enumerate(self.hits, 1):
            rel = os.path.relpath(h.file, self.project_root)
            print(f"  {i:>{w}}  {rel}:{h.line}  {h.decl_name}")

    def do_show(self, arg: str) -> None:
        """show N  —  print the declaration containing sorry #N, with surrounding context."""
        if self._need_hits(): return
        n = self._idx(arg);
        if n is None: return
        h = self.hits[n - 1]
        rel = os.path.relpath(h.file, self.project_root)
        print(f"--- {rel}  (lines {h.decl_range[0]}-{h.decl_range[1]}, decl: {h.decl_name}) ---")
        if h.imports:
            print("--- imports ---")
            print(h.imports)
            print("--- context ---")
        print(h.surrounding)
        if h.diagnostic_message:
            print("--- diagnostic ---")
            print(h.diagnostic_message)

    def do_ask(self, arg: str) -> None:
        """ask N  —  send sorry #N to vLLM and print the candidate proof (does not splice)."""
        if self._need_hits(): return
        n = self._idx(arg)
        if n is None: return
        h = self.hits[n - 1]
        print(f"[agent] asking vLLM about #{n} {h.decl_name}...")
        try:
            p = ask_for_proof(
                h.decl_name,
                h.signature,
                h.surrounding,
                project_context=self.project_context,
                imports=h.imports,
                diagnostic_message=h.diagnostic_message,
                extra_instructions=self.session_instructions,
            )
        except Exception as e:
            print(f"[agent] vLLM call failed: {e}")
            print("[agent] is vllm-up still running? OPENAI_BASE_URL =", os.environ.get("OPENAI_BASE_URL", "(unset)"))
            return
        self.proposals[n] = p
        print(f"[agent] {p.completion_tokens} tokens; model={p.model}")
        print("--- candidate ---")
        print(p.proof)
        print("--- (use `try N` to apply + lake build) ---")

    def do_try(self, arg: str) -> None:
        """try N  —  splice the last candidate for #N, lake build the file; revert on failure."""
        if self._need_hits(): return
        n = self._idx(arg)
        if n is None: return
        if n not in self.proposals:
            print(f"no candidate for #{n} yet; run `ask {n}` first")
            return
        h = self.hits[n - 1]
        p = self.proposals[n]
        target = Path(h.file)
        snapshot = _snapshot(target)
        try:
            patched = splice(target.read_text(encoding="utf-8"), h, p.proof)
            target.write_text(patched, encoding="utf-8")
            module = _module_name_for(self.project_root, target)
            print(f"[agent] lake build {module or '(full project)'}...")
            rc, out, err = lake_build(self.project_root, module)
            if rc == 0:
                print("[agent] OK — leaving change in place.")
            else:
                shutil.copy2(snapshot, target)
                print(f"[agent] BUILD FAILED (rc={rc}); reverted {target.name}.")
                tail = (err.strip() or out.strip()).splitlines()[-20:]
                for line in tail: print("  | " + line)
        finally:
            shutil.rmtree(snapshot.parent, ignore_errors=True)

    def do_build(self, arg: str) -> None:
        """build [MODULE]  —  run `lake build` (whole project, or a specific module)."""
        module = arg.strip() or None
        print(f"[agent] lake build {module or '(full project)'}...")
        rc, out, err = lake_build(self.project_root, module)
        sys.stdout.write(out)
        sys.stderr.write(err)
        print(f"[agent] exit={rc}")

    def do_chat(self, arg: str) -> None:
        """chat QUESTION  —  ask vLLM a free-form question about the project."""
        self._chat(arg)

    def do_q(self, arg: str) -> None:
        """q QUESTION  —  short alias for `chat QUESTION`."""
        self._chat(arg)

    def do_context(self, arg: str) -> None:
        """context  —  print the project context that will be sent to vLLM."""
        include_readme = arg.strip() != "--no-readme"
        print(render_project_context(
            self.project_context,
            extra_instructions=self.session_instructions,
            include_readme=include_readme,
        ))

    def do_refresh_context(self, arg: str) -> None:
        """refresh_context  —  rescan Lake/project metadata and instruction files."""
        print(f"[agent] refreshing context for {self.project_root}...")
        self.project_context = inspect_project(
            self.project_root,
            instructions_path=self.instructions_path,
        )
        print("[agent] context refreshed.")

    def do_instructions(self, arg: str) -> None:
        """instructions [TEXT|@PATH|clear]  —  show/add per-session guidance."""
        raw = arg.strip()
        if not raw:
            if self.project_context.instructions:
                print("--- project instructions ---")
                print(self.project_context.instructions)
            if self.session_instructions:
                print("--- session instructions ---")
                print(self.session_instructions)
            if not self.project_context.instructions and not self.session_instructions:
                print("(no instructions loaded)")
            return
        if raw == "clear":
            self.session_instructions = ""
            print("[agent] session instructions cleared.")
            return
        if raw.startswith("@"):
            path = Path(raw[1:]).expanduser()
            if not path.is_absolute():
                path = self.project_root / path
            text = _read_text_limited(path, max_chars=8000)
            if not text:
                print(f"[agent] no readable instruction text at {path}")
                return
            addition = f"# {path.name}\n{text}"
        else:
            addition = raw
        self.session_instructions = (
            self.session_instructions + "\n\n" + addition
        ).strip()
        print("[agent] session instructions updated.")

    def do_env(self, arg: str) -> None:
        """env  —  print the env vars we care about."""
        print(f"  LEAN_REPO_PATH={os.environ.get('LEAN_REPO_PATH', '(unset)')}")
        print(f"  OPENAI_BASE_URL={_env_label('OPENAI_BASE_URL', DEFAULT_BASE_URL)}")
        print(f"  OPENAI_API_KEY={'set' if os.environ.get('OPENAI_API_KEY') else DEFAULT_API_KEY + ' (default)'}")
        print(f"  VLLM_MODEL={_env_label('VLLM_MODEL', DEFAULT_MODEL)}")
        print(f"  project={self.project_root}")
        if self.project_context.instruction_files:
            print("  instruction_files=" + ", ".join(self.project_context.instruction_files))
        else:
            print("  instruction_files=(none)")

    def do_quit(self, arg: str) -> bool:
        """quit / exit  —  leave the REPL."""
        return True
    do_exit = do_quit
    do_EOF = do_quit

    def default(self, line: str) -> None:
        if line.strip():
            self._chat(line)
            return
        print("type `help` for the command list, or type a project question.")


