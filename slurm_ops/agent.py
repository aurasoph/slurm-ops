def _encode_lsp(msg: dict) -> bytes:
    body = json.dumps(msg).encode("utf-8")
    return f"Content-Length: {len(body)}\r\n\r\n".encode("ascii") + body


class _LeanLSP:
    """Minimal sync LSP client for `lake env lean --server`."""

    def __init__(self, project_root: Path) -> None:
        self.root = project_root.resolve()
        self.proc: Optional[subprocess.Popen] = None
        self._next_id = 1
        self._responses: dict[int, dict] = {}
        self._diagnostics: dict[str, list[dict]] = {}
        self._diag_seen: dict[str, threading.Event] = {}
        self._reader: Optional[threading.Thread] = None
        self._stop = threading.Event()

    def start(self) -> None:
        self.proc = subprocess.Popen(
            ["lake", "env", "lean", "--server"],
            cwd=self.root,
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            bufsize=0,
        )
        self._reader = threading.Thread(target=self._read_loop, daemon=True)
        self._reader.start()
        self._request("initialize", {
            "processId": os.getpid(),
            "rootUri": self.root.as_uri(),
            "capabilities": {
                "textDocument": {
                    "documentSymbol": {"hierarchicalDocumentSymbolSupport": True},
                    "publishDiagnostics": {},
                },
            },
        })
        self._notify("initialized", {})

    def stop(self) -> None:
        if self.proc and self.proc.poll() is None:
            try: self._notify("exit", {})
            except Exception: pass
            self.proc.terminate()
            try: self.proc.wait(timeout=3)
            except subprocess.TimeoutExpired: self.proc.kill()
        self._stop.set()

    def __enter__(self) -> "_LeanLSP":
        self.start(); return self
    def __exit__(self, *exc) -> None:
        self.stop()

    def _send(self, msg: dict) -> None:
        assert self.proc and self.proc.stdin
        self.proc.stdin.write(_encode_lsp(msg)); self.proc.stdin.flush()

    def _notify(self, method: str, params: Any) -> None:
        self._send({"jsonrpc": "2.0", "method": method, "params": params})

    def _request(self, method: str, params: Any, timeout: float = 60.0) -> Any:
        rid = self._next_id; self._next_id += 1
        self._send({"jsonrpc": "2.0", "id": rid, "method": method, "params": params})
        deadline = time.time() + timeout
        while time.time() < deadline:
            if rid in self._responses:
                resp = self._responses.pop(rid)
                if "error" in resp:
                    raise RuntimeError(f"LSP error on {method}: {resp['error']}")
                return resp.get("result")
            time.sleep(0.02)
        raise TimeoutError(f"LSP {method} timed out after {timeout}s")

    def _read_loop(self) -> None:
        assert self.proc and self.proc.stdout
        buf = b""
        try:
            while not self._stop.is_set():
                while b"\r\n\r\n" not in buf:
                    chunk = self.proc.stdout.read(4096)
                    if not chunk: return
                    buf += chunk
                header, _, rest = buf.partition(b"\r\n\r\n")
                clen = 0
                for line in header.split(b"\r\n"):
                    if line.lower().startswith(b"content-length:"):
                        clen = int(line.split(b":", 1)[1].strip())
                while len(rest) < clen:
                    chunk = self.proc.stdout.read(clen - len(rest))
                    if not chunk: return
                    rest += chunk
                body, buf = rest[:clen], rest[clen:]
                msg = json.loads(body.decode("utf-8"))
                self._handle(msg)
        except Exception:
            pass

    def _handle(self, msg: dict) -> None:
        if "id" in msg and ("result" in msg or "error" in msg):
            self._responses[msg["id"]] = msg
        elif msg.get("method") == "textDocument/publishDiagnostics":
            p = msg.get("params", {})
            uri = p.get("uri", "")
            self._diagnostics[uri] = p.get("diagnostics", [])
            ev = self._diag_seen.get(uri)
            if ev is not None: ev.set()

    def open_and_wait(self, path: Path, *, settle_seconds: float = 30.0) -> list[dict]:
        uri = path.as_uri()
        ev = threading.Event()
        self._diag_seen[uri] = ev
        text = path.read_text(encoding="utf-8")
        self._notify("textDocument/didOpen", {
            "textDocument": {"uri": uri, "languageId": "lean", "version": 1, "text": text},
        })
        if not ev.wait(timeout=settle_seconds):
            return self._diagnostics.get(uri, [])
        last_count = -1
        stable_since = time.time()
        while time.time() - stable_since < 3.0:
            cur = len(self._diagnostics.get(uri, []))
            if cur != last_count:
                last_count = cur; stable_since = time.time()
            time.sleep(0.5)
        return self._diagnostics.get(uri, [])

    def document_symbols(self, path: Path) -> list[dict]:
        return self._request("textDocument/documentSymbol", {
            "textDocument": {"uri": path.as_uri()},
        }) or []


