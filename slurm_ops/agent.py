def load_env_file(path: Path) -> dict[str, str]:
    """Parse KEY=value lines from `path`, setdefault into os.environ, return dict.

    Empty lines and lines beginning with `#` are ignored. Surrounding quotes
    are stripped. Existing env vars are NOT overwritten — explicit shell
    exports win.
    """
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, val = line.split("=", 1)
        key = key.strip()
        val = val.strip()
        if (val.startswith('"') and val.endswith('"')) or (val.startswith("'") and val.endswith("'")):
            val = val[1:-1]
        out[key] = val
        os.environ.setdefault(key, val)
    return out


